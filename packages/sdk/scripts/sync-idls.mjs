// `npm run generate`, step 1: this package's committed IDLs and deployments.json → src/generated/.
//
//   idl/carpenter_amm.json
//     → src/generated/idls.ts          (the IDL as a typed constant + IDL_SHA256 over the FILE BYTES)
//     → src/generated/deployments.ts   (deployments.json, validated)
//
// The IDLs are built from the program source (`anchor idl build`) and COPIED into `idl/` with every `docs` field
// removed; this package never builds a program.
// Fails, never warns, when an IDL is missing, when the devnet or local row's program id disagrees with the IDL's
//    `address` (a client generated against the wrong program is the one thing this step must stop), when another
//    row's program id is not a public key, or when a row's derivable account is not its derivation from that row's
//    program ids (`validate-deployments.mjs`).

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateDeployments } from './validate-deployments.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const PROGRAMS = [['carpenter_amm', 'CARPENTER_AMM_IDL', 'carpenterAmm']];

function fail(msg) {
  console.error(`sync-idls: ${msg}`);
  process.exit(1);
}

mkdirSync(join(pkg, 'src/generated'), { recursive: true });
const deployments = JSON.parse(readFileSync(join(pkg, 'deployments.json'), 'utf8'));
if (deployments.version !== 1) fail('deployments.json: version must be 1');
const idlAddress = {};

const hashes = {};
let idlTs = '// GENERATED by scripts/sync-idls.mjs from idl/. Do not edit.\n';
idlTs += "import type { AnchorIdl } from '../deployments.ts';\n\n";
for (const [name, constName, deployKey] of PROGRAMS) {
  const path = join(pkg, 'idl', `${name}.json`);
  let bytes;
  try {
    bytes = readFileSync(path);
  } catch {
    fail(`missing ${path}`);
  }
  const idl = JSON.parse(bytes.toString('utf8'));
  if (idl?.metadata?.name !== name) fail(`${path}: metadata.name is ${idl?.metadata?.name}, expected ${name}`);
  idlAddress[deployKey] = idl.address;
  const sha = createHash('sha256').update(bytes).digest('hex');
  hashes[name] = sha;
  idlTs += `export const ${constName}: AnchorIdl = ${JSON.stringify(idl)};\n\n`;
  console.log(`sync-idls: ${name} ${sha} (${idl.instructions.length} instructions)`);
}
idlTs += `export const IDL_SHA256 = ${JSON.stringify(hashes, null, 2)} as const;\n`;

const problems = await validateDeployments(deployments, idlAddress);
if (problems.length) fail(problems.join('\n  '));
writeFileSync(join(pkg, 'src/generated/idls.ts'), idlTs);
writeFileSync(
  join(pkg, 'src/generated/deployments.ts'),
  '// GENERATED by scripts/sync-idls.mjs from deployments.json. Do not edit.\n' +
    "import type { DeploymentsFile } from '../deployments.ts';\n\n" +
    `export const DEPLOYMENTS: DeploymentsFile = ${JSON.stringify(deployments, null, 2)};\n`,
);
console.log('sync-idls: deployments.json validated');
