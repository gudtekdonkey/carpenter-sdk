// `npm run sync-wasm`: the built quoter wasm → this package.
//
//   <dir>/carpenter_quote_bg.wasm, carpenter_quote.js, carpenter_quote.d.ts[, carpenter_quote_bg.wasm.d.ts]
//     → wasm/<same names>          (byte-for-byte copies) + wasm/SHA256SUMS
//     → src/generated/wasm.ts      (WASM_SHA256, WASM_BYTES)
//
// <dir> is CARPENTER_WASM_DIR, default `../../dist/wasm` (what `wasm/build.sh` at the repository root writes).
// Fails, never warns, when a file is missing, when the glue does not export every function the wrapper calls, or when
// it is not a `--target web` module.

import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { REQUIRED_EXPORTS, WEB_TARGET_MARKERS } from './wasm-exports.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(process.env.CARPENTER_WASM_DIR ?? join(pkg, '../../dist/wasm'));
const out = join(pkg, 'wasm');
const NAMES = ['carpenter_quote_bg.wasm', 'carpenter_quote.js', 'carpenter_quote.d.ts', 'carpenter_quote_bg.wasm.d.ts'];

function fail(msg) {
  console.error(`sync-wasm: ${msg}`);
  process.exit(1);
}

for (const n of NAMES.slice(0, 3)) {
  if (!existsSync(join(src, n))) fail(`missing ${join(src, n)}: run \`bash wasm/build.sh\` at the repository root, or set CARPENTER_WASM_DIR`);
}
const glue = readFileSync(join(src, 'carpenter_quote.js'), 'utf8');
const missing = REQUIRED_EXPORTS.filter((name) => !new RegExp(`export function ${name}\\(`).test(glue));
if (missing.length) fail(`carpenter_quote.js does not export ${missing.join(', ')} (the wasm crate changed; update QuoteFns)`);
const absent = WEB_TARGET_MARKERS.filter(([, re]) => !re.test(glue)).map(([what]) => what);
if (absent.length) fail(`carpenter_quote.js is not a wasm-bindgen --target web module (no ${absent.join(', no ')})`);

const bytes = readFileSync(join(src, 'carpenter_quote_bg.wasm'));
const sha = createHash('sha256').update(bytes).digest('hex');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const n of NAMES) if (existsSync(join(src, n))) copyFileSync(join(src, n), join(out, n));
writeFileSync(join(out, 'SHA256SUMS'), `${sha}  carpenter_quote_bg.wasm\n`);
mkdirSync(join(pkg, 'src/generated'), { recursive: true });
writeFileSync(
  join(pkg, 'src/generated/wasm.ts'),
  '// GENERATED by scripts/sync-wasm.mjs. Do not edit.\n' +
    '/** sha256 of the shipped `wasm/carpenter_quote_bg.wasm`. */\n' +
    `export const WASM_SHA256 = '${sha}';\n` +
    '/** Its size in bytes. */\n' +
    `export const WASM_BYTES = ${bytes.length};\n`,
);
console.log(`sync-wasm: carpenter_quote_bg.wasm ${bytes.length} B sha256 ${sha} → wasm/`);
